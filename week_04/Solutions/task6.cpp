#include <iostream>

int main() {
    char c = 'Z';
    int i = 42;
    double d = 3.14;

    char* pc = &c;
    int* pi = &i;
    double* pd = &d;

    std::cout << "Размер на char: " << sizeof(c) << " байт | Размер на char*: " << sizeof(pc) << " байта\n";
    std::cout << "Размер на int: " << sizeof(i) << " байта  | Размер на int*: " << sizeof(pi) << " байта\n";
    std::cout << "Размер на double: " << sizeof(d) << " байта | Размер на double*: " << sizeof(pd) << " байта\n";

    // Обяснение:
    // Различните типове данни (char, int, double) изискват различен брой байтове
    // за съхранение на техните стойности според диапазона и точността им.
    // Указателите от своя страна съхраняват само адрес от паметта.
    // На 64-битова архитектура адресът винаги е 64 бита (8 байта),
    // независимо от типа данни на стойността, към която сочи.

    return 0;
}
