#include <iostream>

// badSwap приема аргументите по стойност (създават се локални копия на променливите).
// Размяната се извършва единствено върху локалните копия,
// като оригиналните стойности в main() остават непроменени.
void badSwap(int a, int b) {
    int temp = a;
    a = b;
    b = temp;
}

// swap приема аргументите по референция (псевдоними на оригиналните променливи).
// Промените се извършват директно върху оригиналните променливи в main().
void swap(int& a, int& b) {
    int temp = a;
    a = b;
    b = temp;
}

int main() {
    int x = 5;
    int y = 10;

    std::cout << "Първоначално:   x = " << x << ", y = " << y << '\n';

    badSwap(x, y);
    std::cout << "След badSwap:   x = " << x << ", y = " << y << '\n';

    swap(x, y);
    std::cout << "След swap:      x = " << x << ", y = " << y << '\n';

    return 0;
}
